"""Step-by-step assembly instructions with a shelf marking guide.

Inputs: Part and Hardware rows, the layout and derived numbers from model.py.
Outputs: build/instructions.md.
Implements spec 5 (Construction) and the instructions part of 6.5 (Outputs).
"""

import math
from collections import Counter
from pathlib import Path

from materials import Hardware, Part, size


def write_instructions(
    path: Path,
    parts: list[Part],
    hardware: list[Hardware],
    widths: dict[str, float],
    height: float,
    depth: float,
    kickboard_setback: float,
    pocket_spacing: float,
    staple_spacing: float,
    door_gap: float,
    hinge_from_door_end: float,
    knob_from_door_edge: float,
    knob_from_door_top: float,
    kerf: float,
    cutting_list: list[str],
    bolt_heights: list[float],
    layout: list[str],
) -> None:
    """Write instructions.md from the model's parts and numbers."""
    counts = {row.item: row.quantity for row in hardware}
    unit_types = list(dict.fromkeys(p.unit_type for p in parts))
    first = {
        kind: next(p.unit for p in parts if p.unit_type == kind) for kind in unit_types
    }
    units = list(dict.fromkeys(p.unit for p in parts))
    sets = " | ".join("fireplace" if kind == "fireplace" else kind for kind in layout)

    lines = [
        "# Assembly instructions",
        "",
        "Generated by `just build`; do not edit. All measurements in cm.",
        "",
        f"Layout, left to right: {sets}. Units: {', '.join(units)}.",
        "",
        "## 1. Cut",
        "",
        "Follow the cutting list below and the diagrams in `sheets/`. With "
        "a plunge saw: lay each sheet on rigid foam insulation so both sides of every "
        "cut are supported, use about 2.6m of joined track for the full-length rips "
        "and 213cm crosscuts, and tape the cut lines or score first to stop "
        "splintering.",
        f"⚠️ The layout assumes a {size(kerf * 10)}mm saw cut: check your blade's width "
        "and rebuild if it's wider.",
        "",
        *cutting_list,
        "",
        "## 2. Check and label",
        "",
        "Count the panels against this list, then pencil each part's name on an edge "
        "that will be hidden (e.g. `wide_1 / shelf_2`).",
        "",
        "| Part | Unit type | Qty | Size |",
        "| ---- | --------- | --: | ---- |",
    ]
    groups = Counter(
        (p.name, p.unit_type, p.length, p.width, p.thickness) for p in parts
    )
    for (name, kind, length, width, thickness), qty in groups.items():
        lines.append(
            f"| {name} | {kind} | {qty} | {size(length)} × {size(width)} × "
            f"{size(thickness)} |"
        )

    lines += [
        "",
        "## 3. Sand and finish",
        "",
        "Sand both faces and visible edges of every pine panel, then apply the clear "
        "finish while panels are flat. Tape off glue areas: panel ends, the rear "
        "edges the back is glued to, and the shelf lines on the sides. Test on an "
        "offcut first.",
        "",
        "For water-based varnish:",
        "",
        "1. Wipe with a damp cloth to raise the grain; once dry, sand at 240.",
        "2. Stir the can; don't shake it.",
        "3. Roll an even coat with the wool mini roller; swap to a fresh sleeve "
        "when it starts to drag or shed.",
        "4. Tip off at once: drag a near-dry wide synthetic brush lightly along the "
        "grain, end to end in one stroke on long panels.",
        "5. Don't go back over areas that have started to set.",
        "6. Brush the edges.",
        "7. Coat both faces equally so panels don't cup.",
        "",
        "Hardwax oil is wiped on thin and buffed off, not rolled.",
        "",
        "## 4. Mark shelf lines",
        "",
        "Heights from the bottom of the side (the floor). Mark each pair of sides "
        "together, as mirror images, on their inner faces. Fixed shelves leave no room "
        "for error: check every line twice.",
    ]
    for kind in unit_types:
        lines += [
            "",
            f"### {kind.capitalize()} ({size(widths[kind])}cm)",
            "",
            "| Panel | Underside | Top | Depth from front |",
            "| ----- | --------: | --: | ---------------- |",
        ]
        rows = sorted(
            (
                p
                for p in parts
                if p.unit == first[kind] and p.name not in ("side", "back", "door")
            ),
            key=lambda p: p.bottom,
        )
        for p in rows:
            span = (
                f"{size(kickboard_setback)}–{size(kickboard_setback + p.thickness)}"
                if p.name == "kickboard"
                else f"{size(depth - p.width)}–{size(depth)}"
            )
            lines.append(
                f"| {p.label.split(' / ')[1]} | {size(p.bottom)} | {size(p.top)} | "
                f"{span} |"
            )

    lines += [
        "",
        "## 5. Drill pocket holes",
        "",
        "Uses: pocket hole jig.",
        "",
        "Set the jig and the bit's depth collar to each panel's thickness: "
        + ", ".join(
            f"{size(thickness * 10)}mm for "
            + ", ".join(
                dict.fromkeys(
                    p.name
                    for p in parts
                    if p.thickness == thickness
                    and p.name not in ("side", "back", "door")
                )
            )
            for thickness in sorted(
                {p.thickness for p in parts if p.name not in ("side", "back", "door")},
                reverse=True,
            )
        )
        + ". Drill into each end of every panel that sits between the sides, on its "
        "hidden face: the underside of the bottom, cabinet top, cabinet shelf and "
        "open shelves, the top face of the top, the back face of the kickboard. At "
        f"most {size(pocket_spacing)}cm apart. Positions from the panel's front edge:",
        "",
    ]
    for width in sorted(
        {p.width for p in parts if p.name in ("shelf", "cabinet_shelf")}
    ):
        n = max(2, math.ceil(width / pocket_spacing))
        positions = ", ".join(size(width * (i + 0.5) / n) for i in range(n))
        lines.append(f"- {size(width)}cm-deep panels: {positions}")
    kick = next(p for p in parts if p.name == "kickboard")
    kick_n = max(2, math.ceil(kick.width / pocket_spacing))
    lines.append(
        f"- kickboard: {kick_n} per end, at "
        + " and ".join(size(kick.width * (i + 0.5) / kick_n) for i in range(kick_n))
        + " from its bottom edge"
    )

    lines += [
        "",
        "## 6. Assemble each carcass",
        "",
        f"Uses: wood glue, {counts['Wood screws']} wood screws and "
        f"{counts['Short wood screws']} short wood screws, each with a washer, "
        f"{counts['Pocket plugs']} pocket plugs.",
        "",
        "Use the short screws in the thinner panels: a long one can break out through "
        "the outside face of the side.",
        "",
        "Work on the floor with the sides on their rear edges, front edges up. A "
        "screw nudges its panel away from the pocket face as it tightens, so "
        "a shelf with pockets underneath creeps up off its line by a millimetre or "
        "so: clamp the panel to the side, or clamp a block on its line, before "
        "driving. In the narrow units, "
        "check a drill fits between the sides; if not, use a right-angle attachment "
        "or stubby driver.",
        "",
        "1. Glue and screw the bottom and top between the two sides.",
        "2. Add the cabinet top (wide) and the shelves, each on its marked line.",
        f"3. Fit the kickboard under the bottom, {size(kickboard_setback)}cm back from "
        "the front edge.",
        "4. Leave the cabinet shelf until the back is on.",
        "5. Glue plugs into the open shelves' pockets, sand them flush "
        "and varnish them.",
        "",
        "## 7. Square and fix the back",
        "",
        f"Uses: {counts['Staples']} staples in total, wood glue.",
        "",
        "Measure both diagonals of the carcass and push it until they match:",
        "",
    ]
    for kind in unit_types:
        diagonal = math.hypot(widths[kind], height)
        lines.append(f"- {kind}: {size(diagonal)}")
    lines += [
        "",
        "Pencil the shelf lines on the back, then glue and staple it to the rear edges "
        f"of the sides, top, bottom and every shelf, every {size(staple_spacing)}cm. "
        "Keep each staple's crown along the edge, not across it, so a leg can't split "
        "out through a face. The back runs to the floor behind the kickboard.",
        "",
        "## 8. Cabinet shelf, hinges and doors",
        "",
        f"Uses: {counts['Hinges']} hinges, {counts['Knobs']} knobs, short wood screws "
        "with washers.",
        "",
    ]
    door = next((p for p in parts if p.name == "door"), None)
    shelf = next((p for p in parts if p.name == "cabinet_shelf"), None)
    if door and shelf:
        lines += [
            f"1. Fix the cabinet shelf against the back with its underside at "
            f"{size(shelf.bottom)}, leaving {size(depth - shelf.width)}cm at the front "
            "for the hinges.",
            "2. Drill each door's hinge cups "
            f"{size(hinge_from_door_end)}cm from its top and bottom ends, using the "
            "hinge maker's template for the edge distance.",
            f"3. Mount the plates on the sides to match: door bottom at "
            f"{size(door.bottom)}, top at {size(door.top)}.",
            f"4. Hang the doors and adjust for an even {size(door_gap)}cm gap between "
            "the pair.",
            f"5. Fit each knob {size(knob_from_door_edge)}cm from the door's inner "
            f"edge and {size(knob_from_door_top)}cm down from its top.",
        ]
    lines += [
        "",
        "## 9. Install",
        "",
        f"Uses: {counts['Connector bolts']} connector bolts, "
        f"{counts['Anti-tip brackets']} anti-tip brackets, "
        f"{counts['Plasterboard toggles']} plasterboard toggles.",
        "",
        "1. Remove the skirting boards.",
        "2. Stand each unit up with two people; a wide unit is a two-person lift.",
        "3. Bolt each set's two units together through their touching sides, "
        f"{size(depth / 2)}cm from the front edge, at heights "
        + ", ".join(size(h) for h in bolt_heights)
        + ".",
        "4. Fix each unit's anti-tip bracket through its top panel into a stud "
        "wherever possible (find them with a stud finder). Where there's no stud "
        "use spring or snap toggles, never plain plugs. A narrow unit tips very "
        "easily: never skip this.",
        "",
    ]
    path.write_text("\n".join(lines))

"""Step-by-step assembly instructions with a shelf marking guide.

Inputs: Part and Hardware rows, the layout and derived numbers from model.py.
Outputs: build/instructions.md.
Implements spec 5 (Construction) and the instructions part of 6.5 (Outputs).
"""

import math
from collections import Counter
from pathlib import Path

from materials import Hardware, Part, size


def write_instructions(
    path: Path,
    parts: list[Part],
    hardware: list[Hardware],
    widths: dict[str, float],
    unit_width: float,
    height: float,
    shelf_depth: float,
    depth: float,
    kickboard_setback: float,
    pocket_spacing: float,
    back_screw_spacing: float,
    door_gap: float,
    hinge_from_door_end: float,
    knob_from_door_edge: float,
    knob_from_door_top: float,
    kerf: float,
    braces_per_end: int,
    cutting_list: list[str],
    groove_offset: float,
    groove_spacing: float,
    layout: list[str],
    braced: set[str],
) -> None:
    """Write instructions.md from the model's parts and numbers."""
    counts = {row.item: row.quantity for row in hardware}
    bay_types = [k for k in dict.fromkeys(p.unit_type for p in parts) if k != "frame"]
    units = list(dict.fromkeys(p.unit for p in parts))
    sets = ", ".join(layout)
    hidden = ("side", "divider", "back", "door")
    pocketed = [p for p in parts if p.name not in hidden and p.label not in braced]

    lines = [
        "# Assembly instructions",
        "",
        "Generated by `just build`; do not edit. All measurements in cm.",
        "",
        f"Layout, left to right: {sets}. Units: {', '.join(units)}.",
        "",
        "## 1. Cut",
        "",
        "Follow the cutting list below and the diagrams in `sheets/`. With "
        "a plunge saw: lay each sheet on rigid foam insulation so both sides of every "
        "cut are supported, use about 2.6m of joined track for the full-length rips "
        "and 213cm crosscuts, and tape the cut lines or score first to stop "
        "splintering.",
        f"⚠️ The layout assumes a {size(kerf * 10)}mm saw cut: check your blade's width "
        "and rebuild if it's wider.",
        "",
        *cutting_list,
        "",
        "Before ripping each back, measure where the sheet's grooves fall and place "
        f"the cut so a groove sits {size(groove_offset)}cm in from the back's edge on "
        f"the narrow bay's side, then every {size(groove_spacing)}cm. Both bays then "
        "show equal strips at each side, and one groove hides behind the divider.",
        "",
        "## 2. Check and label",
        "",
        "Count the panels against this list, then pencil each part's name on an edge "
        "that will be hidden (e.g. `unit_1 / wide shelf_2`).",
        "",
        "| Part | Unit type | Qty | Size |",
        "| ---- | --------- | --: | ---- |",
    ]
    groups = Counter(
        (p.name, p.unit_type, p.length, p.width, p.thickness) for p in parts
    )
    for (name, kind, length, width, thickness), qty in groups.items():
        lines.append(
            f"| {name} | {kind} | {qty} | {size(length)} × {size(width)} × "
            f"{size(thickness)} |"
        )

    lines += [
        "",
        "## 3. Sand and finish",
        "",
        "Sand both faces and visible edges of every pine panel, then apply the clear "
        "finish while panels are flat. Tape off glue areas: panel ends and the shelf "
        "lines on the sides and divider. Test on an offcut first.",
        "",
        "For water-based varnish:",
        "",
        "1. Wipe with a damp cloth to raise the grain; once dry, sand at 240.",
        "2. Stir the can; don't shake it.",
        "3. Roll an even coat with the wool mini roller; swap to a fresh sleeve "
        "when it starts to drag or shed.",
        "4. Tip off at once: drag a near-dry wide synthetic brush lightly along the "
        "grain, end to end in one stroke on long panels.",
        "5. Don't go back over areas that have started to set.",
        "6. Brush the edges.",
        "7. Coat both faces equally so panels don't cup.",
        "",
        "Hardwax oil is wiped on thin and buffed off, not rolled.",
        "",
        "Paint the backs' grooved face flat, before assembly: one coat of primer "
        f"({counts['Primer (litres)']}L), then one of black "
        f"({counts['Black paint (litres)']}L). Brush into the grooves first, then roll "
        "the face with a spare sleeve, not the varnish one. The back is screwed, not "
        "glued, so nothing needs taping off.",
        "",
        "## 4. Mark shelf lines",
        "",
        "Heights from the floor (the bottom of the side). Each bay's lines go on the "
        "inner face of its outer side and the matching face of the divider; mark them "
        "together, as mirror images. Fixed shelves leave no room for error: check "
        "every line twice.",
    ]
    for kind in bay_types:
        lines += [
            "",
            f"### {kind.capitalize()} bay ({size(widths[kind])}cm inside)",
            "",
            "| Panel | Underside | Top | Depth from front |",
            "| ----- | --------: | --: | ---------------- |",
        ]
        rows = sorted(
            (
                p
                for p in parts
                if p.unit == units[0] and p.unit_type == kind and p.name != "door"
            ),
            key=lambda p: p.bottom,
        )
        for p in rows:
            span = (
                f"{size(kickboard_setback)}–{size(kickboard_setback + p.thickness)}"
                if p.name == "kickboard"
                else f"{size(shelf_depth - p.width)}–{size(shelf_depth)}"
            )
            lines.append(
                f"| {p.label.split(' ')[-1]} | {size(p.bottom)} | {size(p.top)} | "
                f"{span} |"
            )

    lines += [
        "",
        "## 5. Drill pocket holes",
        "",
        "Uses: pocket hole jig.",
        "",
        "Set the jig and the bit's depth collar to each panel's thickness: "
        + ", ".join(
            f"{size(thickness * 10)}mm for "
            + ", ".join(
                dict.fromkeys(p.name for p in pocketed if p.thickness == thickness)
            )
            for thickness in sorted({p.thickness for p in pocketed}, reverse=True)
        )
        + ". Drill into each end of every panel that sits between a side and the "
        "divider (or, for the top, between the two sides), on its hidden face: the "
        "underside of the narrow bay's bottom and the open shelves, the top face of "
        "the top, the back face of the kickboard. The cabinet's bottom, cabinet top "
        "and cabinet shelf get corner braces instead, so no pockets. At most "
        f"{size(pocket_spacing)}cm apart. Positions from the panel's front edge:",
        "",
    ]
    for width in sorted({p.width for p in pocketed if p.name != "kickboard"}):
        n = max(2, math.ceil(width / pocket_spacing))
        positions = ", ".join(size(width * (i + 0.5) / n) for i in range(n))
        lines.append(f"- {size(width)}cm-deep panels: {positions}")
    kick = next(p for p in parts if p.name == "kickboard")
    kick_n = max(2, math.ceil(kick.width / pocket_spacing))
    lines.append(
        f"- kickboard: {kick_n} per end, at "
        + " and ".join(size(kick.width * (i + 0.5) / kick_n) for i in range(kick_n))
        + " from its bottom edge"
    )

    lines += [
        "",
        "## 6. Assemble each carcass",
        "",
        f"Uses: wood glue, {counts['Wood screws']} wood screws and "
        f"{counts['Short wood screws']} short wood screws, each pocket screw with a "
        f"washer, {counts['Pocket plugs']} pocket plugs, "
        f"{counts['Corner braces']} corner braces.",
        "",
        "Use the short screws in the 18mm panels and the long ones in the top. A "
        "screw nudges its panel away from the pocket face as it tightens, so a shelf "
        "with pockets underneath creeps up off its line by a millimetre or so: clamp "
        "the panel to the side, or clamp a block on its line, before driving. In the "
        "narrow bay, check a drill fits; if not, use a right-angle attachment or "
        "stubby driver.",
        "",
        "Build it in the room it stands in. Work on the floor with the sides and "
        "divider on their front edges, rear edges up: every panel is flush at the "
        f"front, and the sides stand {size(depth - shelf_depth)}cm proud at the back "
        "to frame the back panel.",
        "",
        "1. Glue and screw the top between the two sides, then drive "
        "the long screws down through the top into the divider's end.",
        "2. Glue and screw the narrow bay's bottom between its side and the divider, "
        "on its line. In the wide bay, screw corner braces to the side and divider "
        f"with their top faces on the bottom's line, {braces_per_end} per end, set "
        "back from the front edge so the doors and hinges clear them. Glue the "
        "bottom's ends, "
        "set it on the braces and screw up through them into it, with screws no "
        "longer than 15mm so they can't break through the 18mm panel.",
        "3. Fix the cabinet top the same way, on braces under each end, then add the "
        "shelves on their marked lines with pocket screws.",
        f"4. Fit each kickboard under its bottom, {size(kickboard_setback)}cm back "
        "from the front edge.",
        "5. Leave the cabinet shelf until the back is on.",
        "6. Glue plugs into the open shelves' pockets, sand them flush and varnish "
        "them.",
        "",
        "## 7. Square and fix the back",
        "",
        f"Uses: {counts['Back screws']} back screws.",
        "",
        "Measure both diagonals of the carcass and push it until they match: "
        f"{size(math.hypot(unit_width, height))}.",
        "",
        "Pencil the shelf and divider lines on the back. Drop it in between the "
        "sides, under the top, painted face forward and grooves vertical. Drill and "
        "countersink, then screw through it into the rear edges of the divider, "
        f"bottoms, cabinet top and every shelf, every {size(back_screw_spacing)}cm. "
        "No glue. The back runs to the floor behind the kickboards.",
        "",
        "## 8. Cabinet shelf, hinges and doors",
        "",
        f"Uses: {counts['Hinges']} hinges, {counts['Knobs']} knobs, corner braces.",
        "",
    ]
    door = next((p for p in parts if p.name == "door"), None)
    shelf = next((p for p in parts if p.name == "cabinet_shelf"), None)
    if door and shelf:
        lines += [
            f"1. Fix the cabinet shelf on {braces_per_end} corner braces per end, "
            f"against the back with its underside at {size(shelf.bottom)}, leaving "
            f"{size(shelf_depth - shelf.width)}cm at the front for the hinges; screw "
            "through the back into its rear edge too.",
            "2. Drill each door's hinge cups "
            f"{size(hinge_from_door_end)}cm from its top and bottom ends, using the "
            "hinge maker's inset template for the edge distance.",
            "3. Mount the plates on the outer side and the divider to match, set back "
            "by the door's thickness for inset: door bottom at "
            f"{size(door.bottom)}, top at {size(door.top)}.",
            "4. Hang the doors flush with the frame's front and adjust the hinges for "
            f"an even {size(door_gap)}cm gap all round and between the pair. Check "
            "the frame is square first; any twist shows as a tapering gap.",
            f"5. Fit each knob {size(knob_from_door_edge)}cm from the door's inner "
            f"edge and {size(knob_from_door_top)}cm down from its top.",
        ]
    lines += [
        "",
        "## 9. Install",
        "",
        f"Uses: {counts['Anti-tip brackets']} anti-tip brackets, wall fixings.",
        "",
        "1. Remove the skirting boards.",
        "2. Tilt each unit up with at least two people; it is heavy. Standing up, its "
        f"corner sweeps {size(math.hypot(height, depth))}cm, so check the ceiling.",
        "3. Fix each unit's anti-tip bracket through its top panel into a stud "
        "wherever possible (find them with a stud finder). Where there's no stud "
        "use spring or snap toggles, never plain plugs. Never skip this.",
        "",
    ]
    path.write_text("\n".join(lines))

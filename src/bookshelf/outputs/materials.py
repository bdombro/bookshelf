"""materials.md: parts, sheets to buy, hardware and cost, plus the cutting list.

Inputs: Part, Hardware and tool rows, the packing and sheet, saw and price settings.
Outputs: build/materials.md; the cutting list lines for instructions.md.
Implements spec 4 (Materials and cost) and 6.5 (Outputs).
"""

import math
from collections import Counter
from pathlib import Path

from bookshelf.packing.packer import cut_count
from bookshelf.packing.sheets import Packed, SheetSpec
from bookshelf.rows import Hardware, Part
from bookshelf.text import money, size


def hardware_cost(row: Hardware) -> float:
    """Whole packs needed for the count, priced."""
    return math.ceil(row.quantity / row.pack_size) * row.pack_price


def write_materials(
    parts: list[Part],
    hardware: list[Hardware],
    tools: list[Hardware],
    path: Path,
    sheets: dict[str, SheetSpec],
    packed: Packed,
    kerf: float,
    cut_price: float,
    delivery_price: float,
) -> None:
    """Write materials.md: parts, sheets, hardware and the cost estimate."""
    materials = list(packed.counts)
    counts = packed.counts
    cuts = sum(cut_count(packed.packings[m]) for m in materials)
    warning = (
        f"⚠️ **Saw width:** the packing assumes a {size(kerf * 10)}mm saw cut. Panel "
        "saws often cut ~4mm, plunge saws 2.2–2.8mm; confirm the saw width and update "
        "`kerf` before cutting."
    )

    lines = [
        "# Materials",
        "",
        "Generated by `just build`; do not edit. Prices are estimates until quoted.",
        "",
        "## Parts",
        "",
        "| Part | Unit type | Qty | Length × width (cm) | Thickness (cm) | Material |",
        "| ---- | --------- | --: | ------------------- | -------------: | -------- |",
    ]
    groups = Counter(
        (p.name, p.unit_type, p.length, p.width, p.thickness, p.material) for p in parts
    )
    for (name, unit_type, length, width, thickness, material), qty in groups.items():
        lines.append(
            f"| {name} | {unit_type} | {qty} | {size(length)} × {size(width)} | "
            f"{size(thickness)} | {material} |"
        )

    lines += [
        "",
        "## Sheets to buy",
        "",
        "| Material | Sheet (cm) | Count | Area used | Price each | Total |",
        "| -------- | ---------- | ----: | --------: | ---------: | ----: |",
    ]
    sheet_total = 0.0
    for m in materials:
        sheet_length, sheet_width, price, url = sheets[m]
        area = sum(p.length * p.width for p in parts if p.material == m)
        used = area / (counts[m] * sheet_length * sheet_width)
        total = counts[m] * price
        sheet_total += total
        item = f"[{m}]({url})" if url else m
        lines.append(
            f"| {item} | {size(sheet_length)} × {size(sheet_width)} | {counts[m]} | "
            f"{used:.0%} | {money(price)} | {money(total)} |"
        )
    lines += ["", warning]
    lines += [
        "",
        "## Hardware and finish",
        "",
        "| Item | Spec | Count | Packs | Cost |",
        "| ---- | ---- | ----: | ----: | ---: |",
    ]
    hardware_total = 0.0
    for row in hardware:
        cost = hardware_cost(row)
        hardware_total += cost
        packs = math.ceil(row.quantity / row.pack_size)
        item = f"[{row.item}]({row.url})" if row.url else row.item
        spec = ", ".join(s for s in (row.product, row.use) if s)
        lines.append(
            f"| {item} | {spec} | {row.quantity} | {packs} × {row.pack_size} | "
            f"€{cost:,.2f} |"
        )
    lines += [
        "",
        "## Tools",
        "",
        "| Item | Product | Cost |",
        "| ---- | ------- | ---: |",
    ]
    tool_total = 0.0
    for row in tools:
        cost = hardware_cost(row)
        tool_total += cost
        item = f"[{row.item}]({row.url})" if row.url else row.item
        product = ", ".join(s for s in (row.product, row.use) if s)
        lines.append(f"| {item} | {product} | €{cost:,.2f} |")
    cut_total = cuts * cut_price
    total = sheet_total + cut_total + hardware_total + tool_total + delivery_price
    lines += [
        "",
        "## Cost",
        "",
        "All figures are estimates until replaced with quotes.",
        "",
        "| | Estimate |",
        "| - | -------: |",
        f"| Sheets | {money(sheet_total)} |",
        f"| Cutting ({cuts} cuts at {money(cut_price)}) | {money(cut_total)} |"
        if cut_price
        else f"| Cutting ({cuts} cuts, plunge saw under Tools) | €0.00 |",
        f"| Hardware and finish | {money(hardware_total)} |",
        f"| Tools | €{tool_total:,.2f} |",
        f"| Delivery | {money(delivery_price)} |"
        if delivery_price
        else "| Delivery (own pickup) | €0.00 |",
        f"| **Total** | **{money(total)}** |",
        "",
        warning,
        "",
    ]
    path.write_text("\n".join(lines))
